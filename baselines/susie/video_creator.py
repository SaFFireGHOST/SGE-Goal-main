#!/usr/bin/env python3
"""
Create MP4 video from SuSIE subgoal images.

This script takes the sequence of subgoal images generated by the SuSIE pipeline
and combines them into an MP4 video showing the progression from initial state
to final subgoal.
"""

import argparse
import glob
import os
import re
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont


def natural_sort_key(s):
    """Sort strings containing numbers in natural order."""
    return [int(text) if text.isdigit() else text.lower()
            for text in re.split(r'(\d+)', str(s))]


def add_label_to_image(image: Image.Image, label: str, position: str = "top_left") -> Image.Image:
    """Add a small text label to an image at the top left corner."""
    # Create a copy to avoid modifying original
    img = image.copy()
    draw = ImageDraw.Draw(img)
    
    # Try to use a nice font, fall back to default
    try:
        font = ImageFont.truetype("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf", 12)
    except (OSError, IOError):
        try:
            font = ImageFont.truetype("/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf", 12)
        except (OSError, IOError):
            font = ImageFont.load_default()
    
    # Get text bounding box
    bbox = draw.textbbox((0, 0), label, font=font)
    text_width = bbox[2] - bbox[0]
    text_height = bbox[3] - bbox[1]
    
    # Position at top left corner with small padding
    x = 5
    y = 5
    
    # Draw small background rectangle for readability
    padding = 3
    draw.rectangle(
        [x - padding, y - padding, x + text_width + padding, y + text_height + padding],
        fill=(180, 0, 0)  # Dark red background
    )
    
    # Draw text in white
    draw.text((x, y), label, fill=(255, 255, 255), font=font)
    
    return img


def create_video_from_images(
    image_pattern: str,
    output_path: str,
    fps: float = 1.0,
    duration_per_frame: float = None,
    add_labels: bool = True,
    loop_count: int = 1,
    hold_last_frame: float = 2.0,
):
    """
    Create an MP4 video from a sequence of images.
    
    Args:
        image_pattern: Glob pattern or base name to find images 
                      (e.g., "final_subgoal" will match "final_subgoal_iter_*.jpg")
        output_path: Path for output MP4 file
        fps: Frames per second (default: 1.0 for slow progression)
        duration_per_frame: If set, overrides fps (seconds per frame)
        add_labels: Whether to add iteration labels to frames
        loop_count: Number of times to loop the sequence
        hold_last_frame: Extra seconds to hold the final frame
    """
    try:
        import imageio
    except ImportError:
        print("imageio not found. Installing...")
        import subprocess
        subprocess.check_call(["pip", "install", "imageio", "imageio-ffmpeg"])
        import imageio
    
    # Find images matching the pattern
    base_path = Path(image_pattern)
    if base_path.exists() and base_path.is_file():
        # Single file provided, look for iter_* versions
        stem = base_path.stem
        parent = base_path.parent
        suffix = base_path.suffix
        pattern = str(parent / f"{stem}_iter_*{suffix}")
    else:
        # Assume it's a pattern base
        parent = base_path.parent if base_path.parent.exists() else Path(".")
        stem = base_path.stem
        suffix = base_path.suffix if base_path.suffix else ".jpg"
        pattern = str(parent / f"{stem}_iter_*{suffix}")
    
    image_files = sorted(glob.glob(pattern), key=natural_sort_key)
    
    if not image_files:
        # Try without _iter_ pattern
        pattern = str(base_path) + "*"
        image_files = sorted(glob.glob(pattern), key=natural_sort_key)
    
    if not image_files:
        print(f"Error: No images found matching pattern: {pattern}")
        return False
    
    print(f"Found {len(image_files)} images:")
    for f in image_files:
        print(f"  - {f}")
    
    # Load first image to get dimensions
    first_img = Image.open(image_files[0]).convert("RGB")
    width, height = first_img.size
    
    # Calculate FPS
    if duration_per_frame is not None:
        fps = 1.0 / duration_per_frame
    
    # Collect all frames
    frames = []
    
    # Process each image
    for loop in range(loop_count):
        for i, img_path in enumerate(image_files):
            img = Image.open(img_path).convert("RGB")
            
            # Add label if requested
            if add_labels:
                if i == 0:
                    label = "Original"
                elif i == len(image_files) - 1:
                    label = f"Final (iter {i})"
                else:
                    label = f"Iter {i}"
                img = add_label_to_image(img, label)
            
            # Convert to numpy array
            frame = np.array(img)
            frames.append(frame)
    
    # Hold last frame
    if hold_last_frame > 0:
        extra_frames = int(hold_last_frame * fps)
        last_img = Image.open(image_files[-1]).convert("RGB")
        if add_labels:
            last_img = add_label_to_image(last_img, f"Final (iter {len(image_files)-1})")
        last_frame = np.array(last_img)
        for _ in range(extra_frames):
            frames.append(last_frame)
    
    # Write video using imageio
    print(f"\nWriting video with {len(frames)} frames...")
    imageio.mimsave(output_path, frames, fps=fps)
    
    # Calculate duration
    total_duration = len(frames) / fps
    
    print(f"\nVideo created successfully!")
    print(f"  Output: {output_path}")
    print(f"  Resolution: {width}x{height}")
    print(f"  FPS: {fps}")
    print(f"  Total frames: {len(frames)}")
    print(f"  Duration: {total_duration:.1f} seconds")
    
    return True


def main():
    parser = argparse.ArgumentParser(
        description="Create MP4 video from SuSIE subgoal images",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Create video from subgoal images (auto-detect pattern)
  python video_creator.py --input final_subgoal.jpg --output subgoal_video.mp4

  # Custom FPS and no labels
  python video_creator.py --input final_subgoal.jpg --output video.mp4 --fps 2 --no_labels

  # Slower playback with longer hold on final frame
  python video_creator.py --input final_subgoal.jpg --output video.mp4 --duration 2.0 --hold 5.0
        """
    )
    
    parser.add_argument(
        "--input", "-i",
        type=str,
        default="final_subgoal.jpg",
        help="Base name or path of subgoal images (default: final_subgoal.jpg)"
    )
    parser.add_argument(
        "--output", "-o",
        type=str,
        default="susie_subgoal_progression.mp4",
        help="Output video path (default: subgoal_progression.mp4)"
    )
    parser.add_argument(
        "--fps",
        type=float,
        default=1.0,
        help="Frames per second (default: 1.0)"
    )
    parser.add_argument(
        "--duration",
        type=float,
        default=None,
        help="Duration per frame in seconds (overrides --fps)"
    )
    parser.add_argument(
        "--no_labels",
        action="store_true",
        help="Don't add iteration labels to frames"
    )
    parser.add_argument(
        "--loop",
        type=int,
        default=1,
        help="Number of times to loop the sequence (default: 1)"
    )
    parser.add_argument(
        "--hold",
        type=float,
        default=0.0,
        help="Seconds to hold the final frame (default: 0.0)"
    )
    
    args = parser.parse_args()
    
    success = create_video_from_images(
        image_pattern=args.input,
        output_path=args.output,
        fps=args.fps,
        duration_per_frame=args.duration,
        add_labels=not args.no_labels,
        loop_count=args.loop,
        hold_last_frame=args.hold,
    )
    
    if not success:
        exit(1)


if __name__ == "__main__":
    main()
